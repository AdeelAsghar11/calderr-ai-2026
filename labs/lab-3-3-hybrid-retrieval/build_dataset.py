"""
build_dataset.py — Build the RAGAS evaluation dataset  (Lab 3.3 · Friday)

Runs 20 questions through the hybrid RAG pipeline and collects everything
RAGAS needs to evaluate each dimension:

  question       — the user's question
  answer         — what your RAG system generated
  contexts       — the retrieved chunks shown to the LLM
  ground_truth   — a reference answer generated by Groq without context constraints

Saves everything to eval_dataset.json.
Run this once, then run ragas_eval.py as many times as needed.

Commands
--------
  python build_dataset.py build              # all 20 questions
  python build_dataset.py build --subset 5  # quick test with first 5
  python build_dataset.py show              # print the saved dataset
"""

from __future__ import annotations

import json
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")
import time
from pathlib import Path

import typer
from dotenv import find_dotenv, load_dotenv
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_groq import ChatGroq
from rich.console import Console
from rich.panel import Panel
from rich.progress import BarColumn, MofNCompleteColumn, Progress, TextColumn
from rich.table import Table

from hybrid_retriever import HybridRetriever
from reranker import CrossEncoderReranker

load_dotenv(find_dotenv())

app     = typer.Typer(help="Build RAGAS evaluation dataset", add_completion=False)
console = Console()

DATASET_FILE = Path("eval_dataset.json")

# ── 20 evaluation questions ───────────────────────────────────────────────────
# Same questions as chunk_eval.py so results are comparable
QUESTIONS = [
    "What is artificial intelligence?",
    "What happened at the Dartmouth Conference in 1956?",
    "What is supervised learning in machine learning?",
    "What is overfitting and how does it affect model performance?",
    "What is backpropagation and how does it work?",
    "What is a convolutional neural network used for?",
    "What is tokenization in natural language processing?",
    "What is sentiment analysis?",
    "What is a large language model?",
    "What is reinforcement learning from human feedback?",
    "How does the attention mechanism work in transformers?",
    "What is self-attention in transformer models?",
    "What is a vector database and what is it used for?",
    "What is approximate nearest neighbour search?",
    "What is retrieval augmented generation?",
    "What problem does RAG solve in language models?",
    "What is the reward function in reinforcement learning?",
    "What is the difference between model-based and model-free reinforcement learning?",
    "What is image segmentation in computer vision?",
    "What is object detection?",
]

# ── Prompts ───────────────────────────────────────────────────────────────────
RAG_PROMPT = ChatPromptTemplate.from_messages([
    ("system",
     "You are a precise assistant. Answer using ONLY the provided context.\n"
     "If the context lacks the answer, say: 'The documents do not contain this information.'\n"
     "Be concise and factual. 2-4 sentences maximum."),
    ("human", "Context:\n{context}\n\nQuestion: {question}\n\nAnswer:"),
])

GROUND_TRUTH_PROMPT = ChatPromptTemplate.from_messages([
    ("system",
     "You are a knowledgeable AI assistant. Answer the question accurately and concisely.\n"
     "2-4 sentences. No padding, no preamble. Just the factual answer."),
    ("human", "{question}"),
])


# ── Helpers ───────────────────────────────────────────────────────────────────
def get_llm(temperature: float = 0) -> ChatGroq:
    key = os.getenv("GROQ_API_KEY")
    if not key:
        console.print("[red]GROQ_API_KEY not found in .env[/red]")
        raise typer.Exit(1)
    return ChatGroq(model="llama-3.3-70b-versatile", temperature=temperature, api_key=key)


def run_rag(
    question:   str,
    retriever:  HybridRetriever,
    reranker:   CrossEncoderReranker,
    llm:        ChatGroq,
    initial_k:  int = 15,
    final_k:    int = 5,
) -> tuple[str, list[str]]:
    """
    Run one question through hybrid retrieval + rerank + generation.
    Returns (answer_text, list_of_context_strings).
    """
    # Retrieve
    candidates = retriever.retrieve(question, top_k=initial_k)
    ranked     = reranker.rerank(question, candidates, top_k=final_k)
    docs       = [doc for _, doc in ranked]

    # Build context
    context_strings = [doc.page_content for doc in docs]
    context_block   = "\n\n---\n\n".join(
        f"[{doc.metadata.get('topic', doc.metadata.get('source', '?'))}]\n{doc.page_content}"
        for doc in docs
    )

    # Generate answer
    chain  = RAG_PROMPT | llm | StrOutputParser()
    answer = chain.invoke({"context": context_block, "question": question})
    return answer.strip(), context_strings


def generate_ground_truth(question: str, llm: ChatGroq) -> str:
    """
    Generate a reference answer using the LLM's own knowledge (no context).
    This is used as the ground truth for context_recall evaluation.
    The LLM answers from training data — assumed to be accurate for these
    well-known AI/ML topics.
    """
    chain = GROUND_TRUTH_PROMPT | llm | StrOutputParser()
    return chain.invoke({"question": question}).strip()


# ── Commands ──────────────────────────────────────────────────────────────────
@app.command()
def build(
    subset:     int  = typer.Option(0,     "--subset",  "-n",
                                    help="Only process first N questions (0 = all 20)"),
    skip_gt:    bool = typer.Option(False, "--skip-gt",
                                    help="Skip ground truth generation (faster, disables context_recall)"),
    initial_k:  int  = typer.Option(15,    "--initial-k"),
    final_k:    int  = typer.Option(5,     "--final-k"),
) -> None:
    """
    Run all questions through the RAG pipeline and save the evaluation dataset.
    Takes 3-5 minutes for all 20 questions due to LLM calls.
    Use --subset 5 for a quick test run.
    """
    questions = QUESTIONS[:subset] if subset > 0 else QUESTIONS

    console.print()
    console.print(Panel(
        f"[bold]Building RAGAS evaluation dataset[/bold]\n"
        f"Questions: {len(questions)}  |  initial_k={initial_k}  final_k={final_k}\n"
        f"Ground truth: {'[yellow]skipped[/yellow]' if skip_gt else '[green]will generate[/green]'}",
        border_style="blue",
    ))

    # Load models once (expensive)
    console.print("[dim]Loading retriever and reranker...[/dim]")
    retriever = HybridRetriever()
    reranker  = CrossEncoderReranker()
    llm       = get_llm(temperature=0)

    dataset = []

    with Progress(
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        MofNCompleteColumn(),
        console=console,
    ) as progress:
        task = progress.add_task("Processing questions", total=len(questions))

        for i, question in enumerate(questions, 1):
            progress.update(task, description=f"[cyan]Q{i:02d}:[/cyan] {question[:45]}…")

            try:
                # RAG answer + contexts
                answer, contexts = run_rag(question, retriever, reranker, llm, initial_k, final_k)

                # Ground truth
                ground_truth = ""
                if not skip_gt:
                    time.sleep(0.3)  # small delay to avoid rate limiting
                    ground_truth = generate_ground_truth(question, llm)

                dataset.append({
                    "question":     question,
                    "answer":       answer,
                    "contexts":     contexts,
                    "ground_truth": ground_truth,
                })

                progress.advance(task)

            except Exception as e:
                console.print(f"\n[red]Error on Q{i}: {e}[/red]")
                dataset.append({
                    "question":     question,
                    "answer":       f"ERROR: {e}",
                    "contexts":     [],
                    "ground_truth": "",
                })
                progress.advance(task)

    # Save
    DATASET_FILE.write_text(json.dumps(dataset, indent=2, ensure_ascii=False), encoding="utf-8")
    console.print(f"\n[green]✓ Saved {len(dataset)} entries → {DATASET_FILE}[/green]")

    # Preview first entry
    if dataset:
        first = dataset[0]
        console.print(Panel(
            f"[bold]Q:[/bold] {first['question']}\n\n"
            f"[bold]A:[/bold] {first['answer'][:300]}…\n\n"
            f"[bold]Contexts:[/bold] {len(first['contexts'])} chunks\n"
            f"[bold]Ground truth:[/bold] {first['ground_truth'][:150]}…",
            title="Preview — first entry",
            border_style="dim",
        ))
    console.print()


@app.command()
def show() -> None:
    """Print a summary of the saved dataset."""
    if not DATASET_FILE.exists():
        console.print("[red]eval_dataset.json not found. Run: python build_dataset.py build[/red]")
        raise typer.Exit(1)

    data = json.loads(DATASET_FILE.read_text(encoding="utf-8"))

    t = Table(title=f"eval_dataset.json  ({len(data)} entries)", border_style="cyan", show_lines=False)
    t.add_column("#",            style="dim",   width=4)
    t.add_column("Question",     style="white", min_width=40)
    t.add_column("Answer len",   style="green", width=12, justify="right")
    t.add_column("Contexts",     style="cyan",  width=10, justify="right")
    t.add_column("Ground truth", style="dim",   width=12, justify="center")

    for i, row in enumerate(data, 1):
        gt_status = "[green]✓[/green]" if row.get("ground_truth") else "[red]✗[/red]"
        t.add_row(
            str(i),
            row["question"][:55] + ("…" if len(row["question"]) > 55 else ""),
            f"{len(row['answer'])} chars",
            str(len(row["contexts"])),
            gt_status,
        )

    console.print(t)
    console.print()


if __name__ == "__main__":
    if len(sys.argv) == 1:
        app(["build"])
    else:
        app()
